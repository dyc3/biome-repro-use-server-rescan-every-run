import { value29 } from "./module29";
import { value30 } from "./module30";

export const value28 = 28;

export function compute28x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value29;
		} else {
			total -= item - value30;
		}
	}
	return total;
}

