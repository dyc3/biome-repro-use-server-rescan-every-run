import { value26 } from "./module26";
import { value27 } from "./module27";

export const value25 = 25;

export function compute25x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value26;
		} else {
			total -= item - value27;
		}
	}
	return total;
}

