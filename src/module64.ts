import { value65 } from "./module65";
import { value66 } from "./module66";

export const value64 = 64;

export function compute64x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value65;
		} else {
			total -= item - value66;
		}
	}
	return total;
}

