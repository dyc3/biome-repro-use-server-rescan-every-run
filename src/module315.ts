import { value316 } from "./module316";
import { value317 } from "./module317";

export const value315 = 315;

export function compute315x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value316;
		} else {
			total -= item - value317;
		}
	}
	return total;
}

