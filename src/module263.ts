import { value264 } from "./module264";
import { value265 } from "./module265";

export const value263 = 263;

export function compute263x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value264;
		} else {
			total -= item - value265;
		}
	}
	return total;
}

