import { value109 } from "./module109";
import { value110 } from "./module110";

export const value108 = 108;

export function compute108x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value109;
		} else {
			total -= item - value110;
		}
	}
	return total;
}

