import { value101 } from "./module101";
import { value102 } from "./module102";

export const value100 = 100;

export function compute100x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value101;
		} else {
			total -= item - value102;
		}
	}
	return total;
}

