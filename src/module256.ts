import { value257 } from "./module257";
import { value258 } from "./module258";

export const value256 = 256;

export function compute256x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value257;
		} else {
			total -= item - value258;
		}
	}
	return total;
}

