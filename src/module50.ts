import { value51 } from "./module51";
import { value52 } from "./module52";

export const value50 = 50;

export function compute50x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value51;
		} else {
			total -= item - value52;
		}
	}
	return total;
}

