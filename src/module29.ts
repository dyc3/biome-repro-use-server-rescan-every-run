import { value31 } from "./module31";

export const value29 = 29;

export function compute29x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value30;
		} else {
			total -= item - value31;
		}
	}
	return total;
}

