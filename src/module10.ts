import { value11 } from "./module11";
import { value12 } from "./module12";

export const value10 = 10;

export function compute10x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value11;
		} else {
			total -= item - value12;
		}
	}
	return total;
}

