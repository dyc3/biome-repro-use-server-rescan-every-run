import { value98 } from "./module98";
import { value99 } from "./module99";

export const value97 = 97;

export function compute97x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value98;
		} else {
			total -= item - value99;
		}
	}
	return total;
}

