import { value104 } from "./module104";
import { value105 } from "./module105";

export const value103 = 103;

export function compute103x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value104;
		} else {
			total -= item - value105;
		}
	}
	return total;
}

