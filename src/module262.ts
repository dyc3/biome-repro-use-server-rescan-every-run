import { value263 } from "./module263";
import { value264 } from "./module264";

export const value262 = 262;

export function compute262x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value263;
		} else {
			total -= item - value264;
		}
	}
	return total;
}

