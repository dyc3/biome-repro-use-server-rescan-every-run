import { value257 } from "./module257";

export const value255 = 255;

export function compute255x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value256;
		} else {
			total -= item - value257;
		}
	}
	return total;
}

