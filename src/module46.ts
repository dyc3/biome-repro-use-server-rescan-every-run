import { value47 } from "./module47";
import { value48 } from "./module48";

export const value46 = 46;

export function compute46x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value47;
		} else {
			total -= item - value48;
		}
	}
	return total;
}

