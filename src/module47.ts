import { value48 } from "./module48";
import { value49 } from "./module49";

export const value47 = 47;

export function compute47x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value48;
		} else {
			total -= item - value49;
		}
	}
	return total;
}

