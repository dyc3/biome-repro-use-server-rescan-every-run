import { value81 } from "./module81";
import { value82 } from "./module82";

export const value80 = 80;

export function compute80x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value81;
		} else {
			total -= item - value82;
		}
	}
	return total;
}

