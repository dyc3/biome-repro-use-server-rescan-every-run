import { value63 } from "./module63";
import { value64 } from "./module64";

export const value62 = 62;

export function compute62x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value63;
		} else {
			total -= item - value64;
		}
	}
	return total;
}

