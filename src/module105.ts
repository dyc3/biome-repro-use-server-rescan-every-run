import { value107 } from "./module107";

export const value105 = 105;

export function compute105x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value106;
		} else {
			total -= item - value107;
		}
	}
	return total;
}

