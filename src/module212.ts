import { value214 } from "./module214";

export const value212 = 212;

export function compute212x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value213;
		} else {
			total -= item - value214;
		}
	}
	return total;
}

