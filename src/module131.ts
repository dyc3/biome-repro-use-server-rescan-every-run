import { value132 } from "./module132";
import { value133 } from "./module133";

export const value131 = 131;

export function compute131x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value132;
		} else {
			total -= item - value133;
		}
	}
	return total;
}

