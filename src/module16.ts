import { value17 } from "./module17";
import { value18 } from "./module18";

export const value16 = 16;

export function compute16x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value17;
		} else {
			total -= item - value18;
		}
	}
	return total;
}

