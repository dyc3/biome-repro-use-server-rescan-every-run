import { value110 } from "./module110";
import { value111 } from "./module111";

export const value109 = 109;

export function compute109x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value110;
		} else {
			total -= item - value111;
		}
	}
	return total;
}

