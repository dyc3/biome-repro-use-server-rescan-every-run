import { value61 } from "./module61";
import { value62 } from "./module62";

export const value60 = 60;

export function compute60x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value61;
		} else {
			total -= item - value62;
		}
	}
	return total;
}

