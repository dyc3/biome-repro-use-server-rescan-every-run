import { value217 } from "./module217";
import { value218 } from "./module218";

export const value216 = 216;

export function compute216x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value217;
		} else {
			total -= item - value218;
		}
	}
	return total;
}

