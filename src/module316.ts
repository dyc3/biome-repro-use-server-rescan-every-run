import { value317 } from "./module317";
import { value318 } from "./module318";

export const value316 = 316;

export function compute316x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value317;
		} else {
			total -= item - value318;
		}
	}
	return total;
}

