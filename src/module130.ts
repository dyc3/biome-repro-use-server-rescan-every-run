import { value131 } from "./module131";
import { value132 } from "./module132";

export const value130 = 130;

export function compute130x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value131;
		} else {
			total -= item - value132;
		}
	}
	return total;
}

