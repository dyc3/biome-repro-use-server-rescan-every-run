import { value57 } from "./module57";

export const value55 = 55;

export function compute55x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value56;
		} else {
			total -= item - value57;
		}
	}
	return total;
}

