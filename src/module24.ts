import { value25 } from "./module25";
import { value26 } from "./module26";

export const value24 = 24;

export function compute24x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value25;
		} else {
			total -= item - value26;
		}
	}
	return total;
}

