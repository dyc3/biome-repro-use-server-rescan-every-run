import { value95 } from "./module95";
import { value96 } from "./module96";

export const value94 = 94;

export function compute94x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value95;
		} else {
			total -= item - value96;
		}
	}
	return total;
}

