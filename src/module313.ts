import { value314 } from "./module314";
import { value315 } from "./module315";

export const value313 = 313;

export function compute313x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value314;
		} else {
			total -= item - value315;
		}
	}
	return total;
}

