import { value283 } from "./module283";
import { value284 } from "./module284";

export const value282 = 282;

export function compute282x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value283;
		} else {
			total -= item - value284;
		}
	}
	return total;
}

