import { value159 } from "./module159";
import { value160 } from "./module160";

export const value158 = 158;

export function compute158x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value159;
		} else {
			total -= item - value160;
		}
	}
	return total;
}

