import { value312 } from "./module312";
import { value313 } from "./module313";

export const value311 = 311;

export function compute311x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value312;
		} else {
			total -= item - value313;
		}
	}
	return total;
}

