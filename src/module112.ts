import { value113 } from "./module113";
import { value114 } from "./module114";

export const value112 = 112;

export function compute112x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value113;
		} else {
			total -= item - value114;
		}
	}
	return total;
}

