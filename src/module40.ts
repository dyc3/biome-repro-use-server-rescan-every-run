import { value41 } from "./module41";
import { value42 } from "./module42";

export const value40 = 40;

export function compute40x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value41;
		} else {
			total -= item - value42;
		}
	}
	return total;
}

