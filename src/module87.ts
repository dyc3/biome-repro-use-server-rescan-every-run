import { value88 } from "./module88";
import { value89 } from "./module89";

export const value87 = 87;

export function compute87x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value88;
		} else {
			total -= item - value89;
		}
	}
	return total;
}

