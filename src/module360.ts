import { value361 } from "./module361";
import { value362 } from "./module362";

export const value360 = 360;

export function compute360x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value361;
		} else {
			total -= item - value362;
		}
	}
	return total;
}

