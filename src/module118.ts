import { value119 } from "./module119";
import { value120 } from "./module120";

export const value118 = 118;

export function compute118x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value119;
		} else {
			total -= item - value120;
		}
	}
	return total;
}

