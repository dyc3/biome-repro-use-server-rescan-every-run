import { value24 } from "./module24";
import { value25 } from "./module25";

export const value23 = 23;

export function compute23x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value24;
		} else {
			total -= item - value25;
		}
	}
	return total;
}

