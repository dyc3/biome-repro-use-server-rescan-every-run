import { value315 } from "./module315";
import { value316 } from "./module316";

export const value314 = 314;

export function compute314x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value315;
		} else {
			total -= item - value316;
		}
	}
	return total;
}

