import { value97 } from "./module97";
import { value98 } from "./module98";

export const value96 = 96;

export function compute96x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value97;
		} else {
			total -= item - value98;
		}
	}
	return total;
}

