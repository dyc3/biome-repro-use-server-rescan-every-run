import { value28 } from "./module28";
import { value29 } from "./module29";

export const value27 = 27;

export function compute27x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value28;
		} else {
			total -= item - value29;
		}
	}
	return total;
}

