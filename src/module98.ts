import { value99 } from "./module99";
import { value100 } from "./module100";

export const value98 = 98;

export function compute98x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value99;
		} else {
			total -= item - value100;
		}
	}
	return total;
}

