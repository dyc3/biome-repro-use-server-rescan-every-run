import { value34 } from "./module34";
import { value35 } from "./module35";

export const value33 = 33;

export function compute33x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value34;
		} else {
			total -= item - value35;
		}
	}
	return total;
}

