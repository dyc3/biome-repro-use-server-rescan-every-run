import { value116 } from "./module116";
import { value117 } from "./module117";

export const value115 = 115;

export function compute115x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value116;
		} else {
			total -= item - value117;
		}
	}
	return total;
}

