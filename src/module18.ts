import { value19 } from "./module19";
import { value20 } from "./module20";

export const value18 = 18;

export function compute18x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value19;
		} else {
			total -= item - value20;
		}
	}
	return total;
}

