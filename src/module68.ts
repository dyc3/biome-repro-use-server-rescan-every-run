import { value69 } from "./module69";
import { value70 } from "./module70";

export const value68 = 68;

export function compute68x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value69;
		} else {
			total -= item - value70;
		}
	}
	return total;
}

