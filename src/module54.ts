import { value56 } from "./module56";

export const value54 = 54;

export function compute54x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value55;
		} else {
			total -= item - value56;
		}
	}
	return total;
}

