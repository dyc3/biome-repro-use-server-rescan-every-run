import { value15 } from "./module15";
import { value16 } from "./module16";

export const value14 = 14;

export function compute14x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value15;
		} else {
			total -= item - value16;
		}
	}
	return total;
}

