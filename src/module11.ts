import { value12 } from "./module12";
import { value13 } from "./module13";

export const value11 = 11;

export function compute11x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value12;
		} else {
			total -= item - value13;
		}
	}
	return total;
}

