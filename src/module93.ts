import { value95 } from "./module95";

export const value93 = 93;

export function compute93x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value94;
		} else {
			total -= item - value95;
		}
	}
	return total;
}

