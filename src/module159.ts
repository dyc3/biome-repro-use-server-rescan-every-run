import { value160 } from "./module160";
import { value161 } from "./module161";

export const value159 = 159;

export function compute159x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value160;
		} else {
			total -= item - value161;
		}
	}
	return total;
}

