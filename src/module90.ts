import { value91 } from "./module91";
import { value92 } from "./module92";

export const value90 = 90;

export function compute90x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value91;
		} else {
			total -= item - value92;
		}
	}
	return total;
}

