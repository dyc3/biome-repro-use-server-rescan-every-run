import { value115 } from "./module115";
import { value116 } from "./module116";

export const value114 = 114;

export function compute114x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value115;
		} else {
			total -= item - value116;
		}
	}
	return total;
}

