import { value53 } from "./module53";
import { value54 } from "./module54";

export const value52 = 52;

export function compute52x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value53;
		} else {
			total -= item - value54;
		}
	}
	return total;
}

