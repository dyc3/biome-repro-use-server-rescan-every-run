import { value13 } from "./module13";
import { value14 } from "./module14";

export const value12 = 12;

export function compute12x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value13;
		} else {
			total -= item - value14;
		}
	}
	return total;
}

