import { value210 } from "./module210";

export const value208 = 208;

export function compute208x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value209;
		} else {
			total -= item - value210;
		}
	}
	return total;
}

