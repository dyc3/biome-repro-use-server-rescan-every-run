import { value36 } from "./module36";
import { value37 } from "./module37";

export const value35 = 35;

export function compute35x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value36;
		} else {
			total -= item - value37;
		}
	}
	return total;
}

