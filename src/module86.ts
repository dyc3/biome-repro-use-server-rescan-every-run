import { value88 } from "./module88";

export const value86 = 86;

export function compute86x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value87;
		} else {
			total -= item - value88;
		}
	}
	return total;
}

