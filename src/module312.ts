import { value313 } from "./module313";
import { value314 } from "./module314";

export const value312 = 312;

export function compute312x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value313;
		} else {
			total -= item - value314;
		}
	}
	return total;
}

