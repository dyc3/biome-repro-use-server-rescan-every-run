import { value16 } from "./module16";
import { value17 } from "./module17";

export const value15 = 15;

export function compute15x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value16;
		} else {
			total -= item - value17;
		}
	}
	return total;
}

