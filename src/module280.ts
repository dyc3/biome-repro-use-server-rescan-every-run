import { value281 } from "./module281";
import { value282 } from "./module282";

export const value280 = 280;

export function compute280x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value281;
		} else {
			total -= item - value282;
		}
	}
	return total;
}

