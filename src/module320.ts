import { value321 } from "./module321";
import { value322 } from "./module322";

export const value320 = 320;

export function compute320x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value321;
		} else {
			total -= item - value322;
		}
	}
	return total;
}

