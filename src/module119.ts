import { value121 } from "./module121";

export const value119 = 119;

export function compute119x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value120;
		} else {
			total -= item - value121;
		}
	}
	return total;
}

