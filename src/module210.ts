import { value211 } from "./module211";
import { value212 } from "./module212";

export const value210 = 210;

export function compute210x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value211;
		} else {
			total -= item - value212;
		}
	}
	return total;
}

