import { value27 } from "./module27";
import { value28 } from "./module28";

export const value26 = 26;

export function compute26x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value27;
		} else {
			total -= item - value28;
		}
	}
	return total;
}

