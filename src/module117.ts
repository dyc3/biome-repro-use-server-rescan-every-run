import { value119 } from "./module119";

export const value117 = 117;

export function compute117x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value118;
		} else {
			total -= item - value119;
		}
	}
	return total;
}

