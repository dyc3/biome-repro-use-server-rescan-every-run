import { value311 } from "./module311";
import { value312 } from "./module312";

export const value310 = 310;

export function compute310x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value311;
		} else {
			total -= item - value312;
		}
	}
	return total;
}

