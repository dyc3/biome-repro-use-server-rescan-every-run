import { value73 } from "./module73";
import { value74 } from "./module74";

export const value72 = 72;

export function compute72x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value73;
		} else {
			total -= item - value74;
		}
	}
	return total;
}

