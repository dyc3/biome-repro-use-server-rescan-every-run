import { value144 } from "./module144";
import { value145 } from "./module145";

export const value143 = 143;

export function compute143x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value144;
		} else {
			total -= item - value145;
		}
	}
	return total;
}

