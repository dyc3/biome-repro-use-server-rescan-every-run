import { value85 } from "./module85";
import { value86 } from "./module86";

export const value84 = 84;

export function compute84x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value85;
		} else {
			total -= item - value86;
		}
	}
	return total;
}

