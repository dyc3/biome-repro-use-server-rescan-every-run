import { value11 } from "./module11";

export const value9 = 9;

export function compute9x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value10;
		} else {
			total -= item - value11;
		}
	}
	return total;
}

