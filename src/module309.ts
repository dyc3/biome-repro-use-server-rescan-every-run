import { value310 } from "./module310";
import { value311 } from "./module311";

export const value309 = 309;

export function compute309x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value310;
		} else {
			total -= item - value311;
		}
	}
	return total;
}

