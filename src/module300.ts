import { value301 } from "./module301";
import { value302 } from "./module302";

export const value300 = 300;

export function compute300x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value301;
		} else {
			total -= item - value302;
		}
	}
	return total;
}

