import { value35 } from "./module35";
import { value36 } from "./module36";

export const value34 = 34;

export function compute34x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value35;
		} else {
			total -= item - value36;
		}
	}
	return total;
}

