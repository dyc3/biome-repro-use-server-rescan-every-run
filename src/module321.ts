import { value323 } from "./module323";

export const value321 = 321;

export function compute321x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value322;
		} else {
			total -= item - value323;
		}
	}
	return total;
}

