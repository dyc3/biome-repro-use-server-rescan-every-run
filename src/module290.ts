import { value291 } from "./module291";
import { value292 } from "./module292";

export const value290 = 290;

export function compute290x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value291;
		} else {
			total -= item - value292;
		}
	}
	return total;
}

