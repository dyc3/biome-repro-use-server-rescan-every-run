import { value299 } from "./module299";
import { value300 } from "./module300";

export const value298 = 298;

export function compute298x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value299;
		} else {
			total -= item - value300;
		}
	}
	return total;
}

