import { value96 } from "./module96";
import { value97 } from "./module97";

export const value95 = 95;

export function compute95x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value96;
		} else {
			total -= item - value97;
		}
	}
	return total;
}

