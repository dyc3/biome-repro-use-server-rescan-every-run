import { value255 } from "./module255";
import { value256 } from "./module256";

export const value254 = 254;

export function compute254x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value255;
		} else {
			total -= item - value256;
		}
	}
	return total;
}

