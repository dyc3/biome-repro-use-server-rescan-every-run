import { value171 } from "./module171";
import { value172 } from "./module172";

export const value170 = 170;

export function compute170x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value171;
		} else {
			total -= item - value172;
		}
	}
	return total;
}

