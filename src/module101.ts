import { value102 } from "./module102";
import { value103 } from "./module103";

export const value101 = 101;

export function compute101x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value102;
		} else {
			total -= item - value103;
		}
	}
	return total;
}

