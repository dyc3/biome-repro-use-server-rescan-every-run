import { value68 } from "./module68";
import { value69 } from "./module69";

export const value67 = 67;

export function compute67x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value68;
		} else {
			total -= item - value69;
		}
	}
	return total;
}

