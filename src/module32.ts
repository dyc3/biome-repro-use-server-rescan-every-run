import { value33 } from "./module33";
import { value34 } from "./module34";

export const value32 = 32;

export function compute32x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value33;
		} else {
			total -= item - value34;
		}
	}
	return total;
}

