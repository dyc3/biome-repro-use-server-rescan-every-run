import { value103 } from "./module103";
import { value104 } from "./module104";

export const value102 = 102;

export function compute102x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value103;
		} else {
			total -= item - value104;
		}
	}
	return total;
}

