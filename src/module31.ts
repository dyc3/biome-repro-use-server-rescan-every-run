import { value32 } from "./module32";
import { value33 } from "./module33";

export const value31 = 31;

export function compute31x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value32;
		} else {
			total -= item - value33;
		}
	}
	return total;
}

