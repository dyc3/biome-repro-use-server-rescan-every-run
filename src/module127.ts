import { value128 } from "./module128";
import { value129 } from "./module129";

export const value127 = 127;

export function compute127x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value128;
		} else {
			total -= item - value129;
		}
	}
	return total;
}

