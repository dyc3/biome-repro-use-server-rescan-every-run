import { value284 } from "./module284";
import { value285 } from "./module285";

export const value283 = 283;

export function compute283x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value284;
		} else {
			total -= item - value285;
		}
	}
	return total;
}

