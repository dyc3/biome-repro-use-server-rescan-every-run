import { value117 } from "./module117";
import { value118 } from "./module118";

export const value116 = 116;

export function compute116x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value117;
		} else {
			total -= item - value118;
		}
	}
	return total;
}

