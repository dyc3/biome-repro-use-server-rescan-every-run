import { value14 } from "./module14";
import { value15 } from "./module15";

export const value13 = 13;

export function compute13x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value14;
		} else {
			total -= item - value15;
		}
	}
	return total;
}

