import { value31 } from "./module31";
import { value32 } from "./module32";

export const value30 = 30;

export function compute30x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value31;
		} else {
			total -= item - value32;
		}
	}
	return total;
}

