import { value64 } from "./module64";
import { value65 } from "./module65";

export const value63 = 63;

export function compute63x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value64;
		} else {
			total -= item - value65;
		}
	}
	return total;
}

