import { value100 } from "./module100";
import { value101 } from "./module101";

export const value99 = 99;

export function compute99x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value100;
		} else {
			total -= item - value101;
		}
	}
	return total;
}

