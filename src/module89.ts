import { value91 } from "./module91";

export const value89 = 89;

export function compute89x0(items: number[], factor: number): number {
	let total = 0;
	for (const item of items) {
		if (item > factor) {
			total += item * factor + value90;
		} else {
			total -= item - value91;
		}
	}
	return total;
}

